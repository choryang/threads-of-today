  '일본', '대만', '홍콩', '몽골', '러시아', '캄보디아', '라오스', '미얀마', '싱가포르', '네팔', '스리랑카', '파키스탄',
  '이라크', '튀르키예', '터키', '이스라엘', '이집트', '케냐', '탄자니아', '가나', '나이지리아', '남아공', '남아프리카',
  '모로코', '영국', '프랑스', '독일', '이탈리아', '포르투갈', '스위스', '스웨덴', '핀란드', '덴마크', '아일랜드', '벨기에',
  '오스트리아', '폴란드', '우크라이나', '그리스', '캐나다', '멕시코', '콜롬비아', '페루', '아르헨티나', '에콰도르', '과테말라',
