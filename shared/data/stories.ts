/**
 * 핵심 인물 이야기. 규칙과 화면은 docs/key-people.md.
 * 여정마다 세 사람(시작한 손·건너온 손·건네준 손)만 한 화면씩 만나고, 그 화면에 이 이야기를 보여 준다.
 * - story: 한 번만 나오는 사람(출발지 사람 등)의 이야기 한 편
 * - episodes: 여러 여정에 나오는 사람(HUBS·가게 사람). 핵심 자리에서 만날 때마다 다음 편. 다 보면 이야기 칸 없이 작은 기쁨만,
 *   편을 더하면 더한 편부터 이어서 나온다 (shared/key-story.ts). 편 번호·남은 편 수는 화면에 두지 않는다
 * - joy: 그 사람의 작은 기쁨 한 구절
 * 지어낸 이야기다. 실제 날짜·사건·통계는 넣지 않는다. 바다 위 사람은 국적을 쓰지 않는다.
 * 없는 사람은 Person.story(카드 문구)를 그대로 쓴다.
 */

/**
 * 이야기 한 편. moods: 이 편이 담은 마음(shared/data/moods.ts). 오늘 고른 마음과 같은 태그가 붙은 편의 사람을 먼저 만난다
 * (docs/redesign/README.md "한 사람 고르기"). 태그 검토 목록은 docs/redesign/mood-tags.md (npm run mood-tags)
 */
